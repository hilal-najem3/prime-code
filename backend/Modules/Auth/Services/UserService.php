<?php

namespace Modules\Auth\Services;

use Modules\Auth\Models\User;
use Illuminate\Validation\ValidationException;

class UserService
{
    /*
    |--------------------------------------------------------------------------
    | Get All Users
    |--------------------------------------------------------------------------
    */

    public function get(array $filters = [], array $queryParams = [])
    {
        $perPage = $filters['per_page'] ?? null;
        $search = trim($filters['search'] ?? '');
        $sort = $filters['sort'] ?? 'id';
        $direction = strtolower($filters['direction'] ?? 'asc');

        $query = User::query()
            ->when($search !== '', function ($query) use ($search) {
                $query->where(function ($subQuery) use ($search) {
                    $subQuery->where('name', 'like', "%{$search}%")
                        ->orWhere('email', 'like', "%{$search}%")
                        ->orWhere('enabled', 'like', "%{$search}%");
                });
            })
            ->orderBy($sort, $direction);

        return $perPage
            ? $query->paginate($perPage)->appends($queryParams)
            : $query->get();
    }

    /*
    |--------------------------------------------------------------------------
    | Create User
    |--------------------------------------------------------------------------
    */

    public function create(array $data): User
    {
        /*
        |--------------------------------------------------------------------------
        | Extract Roles
        |--------------------------------------------------------------------------
        */

        $roles = $data['roles'] ?? [];
        unset($data['roles']);

        /*
        |--------------------------------------------------------------------------
        | Create User
        |--------------------------------------------------------------------------
        */

        $user = User::create([
            ...$data,
            'password' => $data['password'], // auto hashed via cast
        ]);

        /*
        |--------------------------------------------------------------------------
        | Sync Roles
        |--------------------------------------------------------------------------
        */

        if (!empty($roles)) {
            $user->roles()->sync($roles);
        }

        /*
        |--------------------------------------------------------------------------
        | Clear Cache
        |--------------------------------------------------------------------------
        */

        $user->clearPermissionCache();

        return $user->load('roles');
    }

    /*
    |--------------------------------------------------------------------------
    | Update User
    |--------------------------------------------------------------------------
    */

    public function update(User $user, array $data): User
    {
        /*
        |--------------------------------------------------------------------------
        | Extract Roles
        |--------------------------------------------------------------------------
        */

        $roles = $data['roles'] ?? null;
        unset($data['roles']);

        /*
        |--------------------------------------------------------------------------
        | Handle Password
        |--------------------------------------------------------------------------
        */

        if (empty($data['password'])) {
            unset($data['password']);
        }

        /*
        |--------------------------------------------------------------------------
        | Update User
        |--------------------------------------------------------------------------
        */

        $user->update($data);

        /*
        |--------------------------------------------------------------------------
        | Sync Roles (IMPORTANT)
        |--------------------------------------------------------------------------
        */

        if (is_array($roles)) {
            $user->roles()->sync($roles);
        }

        /*
        |--------------------------------------------------------------------------
        | Clear Cache
        |--------------------------------------------------------------------------
        */

        $user->clearPermissionCache();

        return $user->load('roles');
    }

    /*
    |--------------------------------------------------------------------------
    | Delete User
    |--------------------------------------------------------------------------
    */

    public function delete(User $user): void
    {
        /*
        |--------------------------------------------------------------------------
        | Prevent Self Delete
        |--------------------------------------------------------------------------
        */

        if ($user->id === user_id()) {
            throw ValidationException::withMessages([
                'user' => ['You cannot delete yourself.']
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | Detach Roles (optional but clean)
        |--------------------------------------------------------------------------
        */

        $user->roles()->detach();

        /*
        |--------------------------------------------------------------------------
        | Delete (Soft Delete)
        |--------------------------------------------------------------------------
        */

        $user->delete();

        /*
        |--------------------------------------------------------------------------
        | Clear Cache
        |--------------------------------------------------------------------------
        */

        $user->clearPermissionCache();
    }

    /*
    |--------------------------------------------------------------------------
    | Toggle Enabled
    |--------------------------------------------------------------------------
    */

    public function toggle(User $user): User
    {
        $user->update([
            'enabled' => !$user->enabled
        ]);

        $user->clearPermissionCache();

        return $user;
    }
}
